import type { Grade } from "../types";

// 国語の教科別プロンプト。学年ごとに扱ってよい範囲を明示する。
export function japaneseSubjectPolicy(grade: Grade): string {
  const scopeByGrade: Record<Grade, string> = {
    1: "漢字の読み書き、語句（熟語の構成・対義語・類義語・慣用句）、文法の基礎（文節・主語述語・修飾語・品詞の名前）、歴史的仮名遣いと古典入門（中1範囲）",
    2: "用言の活用、助詞・助動詞、敬語の基礎、漢文訓読の基礎（中2までの範囲）",
    3: "文法のまとめ、和歌・俳句、課題作文（中3までの範囲）",
  };
  return `【教科: 国語】
- 扱ってよい知識は「${scopeByGrade[grade]}」まで。高校で習う文法用語や古典文法の細かい活用などは使わない。
- 漢字の問題では、答えの漢字や読みそのものをヒントで書かない。部首・画数・意味・使われる場面など、思い出す手がかりへ導く。
- 文法の問題では、「ネ」を入れて区切る、言い切りの形にしてみる、など教科書で習う手順を思い出させる。
- 古典では、現代の言葉とのつながり（例: 仮名遣いの変換ルール）に気づかせる。`;
}
