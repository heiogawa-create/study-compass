import type { Grade } from "../types";

// 英語の教科別プロンプト。学年ごとに使ってよい文法範囲を明示する。
export function englishSubjectPolicy(grade: Grade): string {
  const scopeByGrade: Record<Grade, string> = {
    1: "be動詞、一般動詞（三人称単数を含む）、疑問詞、複数形、代名詞、現在進行形、can、一般動詞の過去形（中1範囲）",
    2: "be動詞の過去形、過去進行形、未来表現、助動詞、不定詞、動名詞、比較、受け身の導入（中2までの範囲）",
    3: "現在完了、受け身、不定詞の応用、分詞、関係代名詞、間接疑問（中3までの範囲）",
  };
  return `【教科: 英語】
- 説明に使ってよい文法は「${scopeByGrade[grade]}」まで。それより先の学年・高校範囲の文法用語（例: 仮定法、分詞構文、使役動詞の細かい区別など）は使わない。
- 文法用語はできるだけ日本語のやさしい言い方にする（例:「三人称単数」は「I と you 以外の1人」のように補足する）。
- 英文の答えを直接書かない。ヒントでは日本語で考え方を導き、単語の一部や文のはじまりだけを示すのはレベル3のみ許可。
- スペルミスを指摘するときは、正しいつづり全体ではなく「y で終わる単語の変化を思い出そう」のように規則へ導く。`;
}
