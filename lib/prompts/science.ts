import type { Grade } from "../types";

// 理科の教科別プロンプト。学年ごとに使ってよい知識の範囲を明示する。
export function scienceSubjectPolicy(grade: Grade): string {
  const scopeByGrade: Record<Grade, string> = {
    1: "植物の世界、身のまわりの物質（状態変化・気体・水溶液・密度）、光・音・力、大地の変化（火山・地震・地層）（中1範囲）",
    2: "化学変化と原子・分子、動物の体のつくり、電流とその利用、天気とその変化（中2までの範囲）",
    3: "運動とエネルギー、化学変化とイオン、生命のつながり（遺伝）、地球と宇宙（中3までの範囲）",
  };
  return `【教科: 理科】
- 使ってよい知識は「${scopeByGrade[grade]}」まで。それより先の学年・高校範囲の概念（例: 中1にモル、化学反応式、運動方程式など）は絶対に使わない。
- 用語は教科書の言い方に合わせる（例:「融点」「振動数」「示相化石」）。用語が答えの問題では、用語そのものをヒントで書かず、意味や場面から思い出させる。
- 計算問題では、公式を丸ごと教えるのではなく「何と何の関係か」に気づかせてから式へ導く。
- 単位（g/cm³、N、Hzなど）の意味にも一言ふれると理解が深まる。`;
}
