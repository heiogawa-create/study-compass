import type { Grade } from "../types";

// 社会の教科別プロンプト。学年ごとに扱ってよい範囲を明示する。
export function socialSubjectPolicy(grade: Grade): string {
  const scopeByGrade: Record<Grade, string> = {
    1: "世界の姿（大陸・海洋・緯度経度・時差）、世界の気候と暮らし、歴史のはじまり（古代文明〜弥生・古墳）、古代国家の歩み（飛鳥〜平安）（中1範囲）",
    2: "日本の姿と諸地域、中世〜近世の歴史（鎌倉〜江戸）（中2までの範囲）",
    3: "公民（現代社会・憲法・政治・経済）、近現代の歴史（中3までの範囲）",
  };
  return `【教科: 社会】
- 扱ってよい知識は「${scopeByGrade[grade]}」まで。高校の詳細な内容（細かい年号論争や高校地理・日本史の用語）には踏みこまない。
- 用語が答えの問題では、用語そのものをヒントで書かない。時代・場所・人物・「なぜそうなったか」の因果関係から思い出させる。
- 歴史では出来事のつながり（原因→結果）を、地理では「気候や地形が暮らしをどう決めるか」という見方を大切にする。
- 人名・地名は教科書の表記に合わせる。`;
}
