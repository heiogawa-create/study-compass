import type { Grade } from "../types";

// 数学の教科別プロンプト。学年ごとに使ってよい知識の範囲を明示する。
export function mathSubjectPolicy(grade: Grade): string {
  const scopeByGrade: Record<Grade, string> = {
    1: "正負の数、文字と式、一次方程式、比例と反比例、平面図形、空間図形、データの活用（中1範囲）",
    2: "式の計算、連立方程式、一次関数、図形の性質と合同、確率（中2までの範囲）",
    3: "多項式、平方根、二次方程式、関数 y=ax^2、相似、三平方の定理、標本調査（中3までの範囲）",
  };
  return `【教科: 数学】
- 使ってよい知識は「${scopeByGrade[grade]}」まで。それより先の学年・高校範囲の解法（例: 因数分解の公式を中1に使う、二次方程式の解の公式、微分、三角関数など）は絶対に使わない。
- 用語は教科書の言い方に合わせる（例:「移項」「分配法則」「絶対値」）。
- 計算の考え方を示すときは、なぜそうするのかの理由を一言添える。
- 数式は 3x − 6 のようなふつうの文字表記で書く（LaTeXや特殊記号は使わない）。`;
}
